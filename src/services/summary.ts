import { APP_NAME } from "@/config/app";
import type { Scan } from "@/types/scan";

export const SHARE_FOOTER = `Generated by ${APP_NAME}. This is a screening estimate, not a diagnostic report, and must not be used as the sole basis for medical decisions.`;

export function formatCaptured(iso: string) {
  const d = new Date(iso);
  const today = new Date().toDateString() === d.toDateString();
  const time = d.toLocaleTimeString([], { hour: "numeric", minute: "2-digit" });
  return today ? `Captured today at ${time}` : `Captured ${d.toLocaleDateString([], { day: "numeric", month: "short", year: "numeric" })} at ${time}`;
}

export const fmt = (n: number, digits = 1) => n.toLocaleString(undefined, { maximumFractionDigits: digits, minimumFractionDigits: digits });

export function shortResult(scan: Scan): string {
  const a = scan.analysis;
  if (a.status !== "complete" || a.albuminMgL == null || a.creatinineMgL == null || a.acr == null) return "No result";
  return `Albumin ${fmt(a.albuminMgL)} mg/L · Creatinine ${fmt(a.creatinineMgL)} mg/L · ACR ${fmt(a.acr)}`;
}

export function buildSummary(scan: Scan): string {
  return [
    `${APP_NAME} — screening estimate summary`,
    formatCaptured(scan.createdAt),
    `Photo quality: ${scan.quality.label}`,
    "",
    shortResult(scan),
    "",
    "Screening estimate only. Compare with the manufacturer's chart and seek professional advice when needed.",
    "",
    SHARE_FOOTER,
  ].join("\n");
}
