import { APP_NAME } from "@/config/app";
import type { Scan } from "@/types/scan";
import { getConfigurationById, configurationStatusLabel } from "./referenceConfigService";

export const SHARE_FOOTER = `Generated by ${APP_NAME} in demo mode. This is not a diagnostic report and must not be used as the sole basis for medical decisions.`;

export function formatCaptured(iso: string) {
  const d = new Date(iso);
  const today = new Date().toDateString() === d.toDateString();
  const time = d.toLocaleTimeString([], { hour: "numeric", minute: "2-digit" });
  return today ? `Captured today at ${time}` : `Captured ${d.toLocaleDateString([], { day: "numeric", month: "short", year: "numeric" })} at ${time}`;
}

export function levelName(scan: Scan, padId: string) {
  const cfg = getConfigurationById(scan.configuration.id);
  const pad = scan.pads.find((p) => p.id === padId);
  const level = cfg?.pads.find((p) => p.id === padId)?.levels.find((l) => l.id === pad?.resultLevel);
  return level?.displayName ?? "No reliable estimate";
}

export function buildSummary(scan: Scan): string {
  const cfg = getConfigurationById(scan.configuration.id);
  const lines = [
    `${APP_NAME} — screening estimate summary`,
    formatCaptured(scan.createdAt),
    `Configuration: ${cfg?.stripName ?? scan.configuration.id} (${configurationStatusLabel(scan.configuration)})`,
    `Photo quality: ${scan.quality.label}`,
    "",
    ...scan.pads.map((p) => {
      const pad = cfg?.pads.find((c) => c.id === p.id);
      return `${pad?.label ?? p.id} (${pad?.description ?? ""}): ${levelName(scan, p.id)} — colour match ${p.matchConfidence ?? "–"}%`;
    }),
    "",
    "Screening estimate only. Compare with the manufacturer's chart and seek professional advice when needed.",
    "",
    SHARE_FOOTER,
  ];
  return lines.join("\n");
}
